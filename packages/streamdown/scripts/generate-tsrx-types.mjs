import {
	existsSync,
	mkdirSync,
	mkdtempSync,
	readdirSync,
	readFileSync,
	rmSync,
	symlinkSync,
	writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import ts from 'typescript';

const packageRoot = resolve(import.meta.dirname, '..');
const sourceRoot = join(packageRoot, 'src');
const checking = process.argv.includes('--check');
const outputFlagIndex = process.argv.indexOf('--out-dir');
const outputRoot =
	outputFlagIndex === -1 ? null : resolve(packageRoot, process.argv[outputFlagIndex + 1] ?? '');

if (outputFlagIndex !== -1 && process.argv[outputFlagIndex + 1] === undefined) {
	throw new Error('Missing directory after --out-dir.');
}
if (checking && outputRoot !== null) {
	throw new Error('--check and --out-dir cannot be used together.');
}

function filesUnder(directory) {
	return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
		const path = join(directory, entry.name);
		return entry.isDirectory() ? filesUnder(path) : [path];
	});
}

function replaceRelativeSpecifiers(source, transform) {
	return source.replace(
		/(\b(?:from\s*|import\s*\(\s*|require\s*\(\s*)['"])(\.{1,2}\/[^'"]+)(['"])/g,
		(match, before, specifier, after) => `${before}${transform(specifier)}${after}`,
	);
}

const sources = filesUnder(sourceRoot).filter(
	(file) =>
		(file.endsWith('.ts') || file.endsWith('.tsrx')) &&
		!file.endsWith('.d.ts') &&
		!file.endsWith('.tsrx.d.ts'),
);
const components = sources.filter((file) => file.endsWith('.tsrx'));
const temporaryRoot = mkdtempSync(join(tmpdir(), 'octane-streamdown-types-'));
const temporarySource = join(temporaryRoot, 'src');
const temporaryOutput = join(temporaryRoot, 'out');

try {
	symlinkSync(join(packageRoot, 'node_modules'), join(temporaryRoot, 'node_modules'), 'dir');

	for (const file of sources) {
		const relativePath = relative(sourceRoot, file).replace(/\.tsrx$/, '.tsx');
		const target = join(temporarySource, relativePath);
		const source = replaceRelativeSpecifiers(readFileSync(file, 'utf8'), (specifier) =>
			specifier.endsWith('.tsrx') ? specifier.replace(/\.tsrx$/, '.tsx') : specifier,
		);
		mkdirSync(dirname(target), { recursive: true });
		writeFileSync(target, source);
	}

	const roots = (outputRoot === null ? components : sources).map((file) =>
		join(temporarySource, relative(sourceRoot, file).replace(/\.tsrx$/, '.tsx')),
	);
	const program = ts.createProgram(roots, {
		declaration: true,
		emitDeclarationOnly: true,
		esModuleInterop: true,
		jsx: ts.JsxEmit.ReactJSX,
		jsxImportSource: 'octane',
		module: ts.ModuleKind.ESNext,
		moduleResolution: ts.ModuleResolutionKind.Bundler,
		noCheck: true,
		outDir: temporaryOutput,
		preserveSymlinks: true,
		rootDir: temporarySource,
		skipLibCheck: true,
		strictNullChecks: true,
		target: ts.ScriptTarget.ESNext,
		types: ['node'],
	});
	const result = program.emit();
	if (result.emitSkipped) {
		const diagnostics = [...ts.getPreEmitDiagnostics(program), ...result.diagnostics]
			.map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'))
			.join('\n');
		throw new Error(`TypeScript skipped Streamdown declaration generation.\n${diagnostics}`);
	}

	if (outputRoot !== null) {
		for (const source of sources) {
			const sourcePath = relative(sourceRoot, source).replace(/\.tsrx$/, '.tsx');
			const emitted = join(temporaryOutput, sourcePath.replace(/\.(?:ts|tsx)$/, '.d.ts'));
			const destination = join(outputRoot, sourcePath.replace(/\.(?:ts|tsx)$/, '.d.ts'));
			const declaration =
				`// Generated by scripts/generate-tsrx-types.mjs for the built package.\n${replaceRelativeSpecifiers(
					readFileSync(emitted, 'utf8'),
					(specifier) => specifier.replace(/\.(?:ts|tsx)$/, '.js'),
				)}`.replace(/[ \t]+$/gm, '');
			mkdirSync(dirname(destination), { recursive: true });
			writeFileSync(destination, declaration);
		}
		console.log(
			`Streamdown package declarations emitted (${sources.length} modules) to ${relative(
				packageRoot,
				outputRoot,
			)}.`,
		);
		process.exitCode = 0;
	} else {
		const changed = [];
		for (const component of components) {
			const emitted = join(
				temporaryOutput,
				relative(sourceRoot, component).replace(/\.tsrx$/, '.d.ts'),
			);
			const declaration =
				`// Generated by scripts/generate-tsrx-types.mjs.\n${replaceRelativeSpecifiers(
					readFileSync(emitted, 'utf8'),
					(specifier) =>
						specifier.endsWith('.tsx') ? specifier.replace(/\.tsx$/, '.tsrx') : specifier,
				)}`.replace(/[ \t]+$/gm, '');
			const destination = `${component}.d.ts`;

			if (!existsSync(destination) || readFileSync(destination, 'utf8') !== declaration) {
				changed.push(relative(packageRoot, destination));
				if (!checking) {
					writeFileSync(destination, declaration);
				}
			}
		}

		if (checking && changed.length > 0) {
			throw new Error(`Stale Streamdown TSRX declarations:\n${changed.join('\n')}`);
		}
		console.log(`Streamdown TSRX declarations are current (${components.length} components).`);
	}
} finally {
	rmSync(temporaryRoot, { force: true, recursive: true });
}
