#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync, mkdirSync, unlinkSync } from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import { createTypeEvidenceProgram } from './type-program.mjs';
import { concretePublicSpecifiers } from './public-exports.mjs';
import { pinnedPublicEntries, publicSymbolType } from './pinned-public-types.mjs';

const directory = path.resolve(process.argv[2]);
const manifest = JSON.parse(readFileSync(path.join(directory, 'package.json'), 'utf8'));
const lock = JSON.parse(readFileSync(path.join(directory, 'audit/upstream.lock.json'), 'utf8'));
const extensionsPath = path.join(directory, 'audit/published-contract-extensions.json');
const extensions = existsSync(extensionsPath)
	? JSON.parse(readFileSync(extensionsPath, 'utf8'))
	: {};
const callableArityExtensions = extensions.callableArity ?? {};
const additionalExports = extensions.additionalExports ?? {};

function literalUnion(type, checker) {
	const parts = type.isUnion?.() ? type.types : [type];
	return parts
		.map(function (part) {
			return checker.typeToString(part, undefined, ts.TypeFormatFlags.NoTruncation);
		})
		.sort()
		.join(' | ');
}

function unionMembers(union) {
	return new Set(
		union.split('|').map(function (part) {
			return part.trim();
		}),
	);
}
const entries = pinnedPublicEntries(directory, { identity: lock.identity, binding: manifest.name });
const specifiers = concretePublicSpecifiers(directory, manifest.name);
const folder = path.join(directory, 'tests/types');
mkdirSync(folder, { recursive: true });
const probe = path.join(folder, '.public-contract-probe.ts');
const imports = specifiers.flatMap((specifier, index) => [
	`import type * as Native${index} from '${specifier}';`,
	`import type * as Upstream${index} from '${specifier.replace(manifest.name, lock.identity.packageName)}';`,
]);

function argumentsFor(symbol) {
	const declaration = symbol.declarations?.find((node) => node.typeParameters?.length);
	const required = (declaration?.typeParameters ?? []).filter((parameter) => !parameter.default);
	if (!required.length) return '';
	const arguments_ = required.map((parameter) => {
		const constraint = parameter.constraint?.getText();
		switch (constraint) {
			case undefined:
			case 'object':
				return '{ sample: string }';
			case 'string':
			case 'string | null':
				return "'sample'";
			case 'React.ElementType':
				return "'div'";
			case 'Element':
				return 'HTMLDivElement';
			case 'Event':
				return 'MouseEvent';
			case 'boolean | undefined':
				return 'true';
			case 'keyof T':
				return "'sample'";
			case 'TemporalSupportedValue':
				return 'Date';
			default:
				throw new Error(
					`Choose a concrete consumer for ${symbol.name}.${parameter.name.getText()}: ${constraint}`,
				);
		}
	});
	return `<${arguments_.join(', ')}>`;
}

try {
	writeFileSync(probe, imports.join('\n'));
	const config = ts.readConfigFile(path.join(directory, 'tsconfig.json'), ts.sys.readFile);
	const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, directory);
	const program = createTypeEvidenceProgram([probe, ...entries.values()], parsed.options);
	const checker = program.getTypeChecker();
	const assertions = [];
	const output = [
		'/** @jsxImportSource octane */',
		'// Generated by scripts/react-port/generate-public-contract-tests.mjs.',
		'// Every published export participates in a consumer assertion against the pinned npm types.',
		'// Property presence and callable arity complement the recursive opacity audit,',
		'// the complete upstream type suite, and the handwritten inference/negative examples.',
		"import type { Assert, Equal } from '../../../../scripts/react-port/type-assertions';",
		...imports.filter((_, index) => index % 2 === 0),
		'',
	];
	let count = 0;
	const extraProofs = [];
	for (const [index, specifier] of specifiers.entries()) {
		const statement = program.getSourceFile(probe).statements[index * 2];
		const module = checker.getSymbolAtLocation(statement.moduleSpecifier);
		const originalSource = program.getSourceFile(entries.get(specifier));
		const originalModule = checker.getSymbolAtLocation(originalSource);
		const originals = new Map(
			checker.getExportsOfModule(originalModule).map((symbol) => [symbol.name, symbol]),
		);
		for (const symbol of checker.getExportsOfModule(module)) {
			const original = originals.get(symbol.name);
			if (!original) {
				const extra = additionalExports[`${specifier}#${symbol.name}`];
				if (extra) {
					extraProofs.push({
						id: `Extra${extraProofs.length}`,
						native: `typeof Native${index}.${symbol.name}`,
						length: extra.arity ?? extra.length,
						reason: extra.reason,
						name: symbol.name,
					});
					continue;
				}
				throw new Error(`Export absent from the pinned npm contract: ${specifier}.${symbol.name}`);
			}
			const resolved =
				symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
			const typeOnly = Boolean(
				resolved.flags & (ts.SymbolFlags.TypeAlias | ts.SymbolFlags.Interface),
			);
			const arguments_ = typeOnly ? argumentsFor(resolved) : '';
			const native = `${typeOnly ? '' : 'typeof '}Native${index}.${symbol.name}${arguments_}`;
			const upstreamArguments = arguments_.replaceAll(
				'MouseEvent',
				"import('react').MouseEvent<HTMLElement>",
			);
			const upstream = `${typeOnly ? '' : 'typeof '}Upstream${index}.${symbol.name}${upstreamArguments}`;
			const type = publicSymbolType(original, checker);
			const context = (type.aliasSymbol ?? type.symbol)?.name === 'Context';
			const callable =
				!context && checker.getSignaturesOfType(type, ts.SignatureKind.Call).length > 0;
			const right = callable ? `Parameters<${upstream}>['length']` : `keyof ${upstream}`;
			const originalSymbol =
				original.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(original) : original;
			const originalDeclaration =
				originalSymbol.valueDeclaration ?? originalSymbol.declarations?.[0];
			const platformQuery =
				originalDeclaration?.type &&
				ts.isTypeQueryNode(originalDeclaration.type) &&
				originalDeclaration.type.exprName.getText();
			const platform =
				typeof platformQuery === 'string' && /^React(?:\.[A-Za-z]+)?$/.test(platformQuery)
					? `typeof import('octane')${platformQuery.slice('React'.length)}`
					: undefined;
			assertions.push({
				id: count++,
				native,
				right,
				nativeArityRight: callable ? `Parameters<${native}>['length']` : undefined,
				callable,
				name: symbol.name,
				specifier,
				context,
				platform,
			});
		}
	}
	const witnessAliases = [];
	for (const assertion of assertions) {
		witnessAliases.push(`type Witness${assertion.id} = ${assertion.right};`);
		if (assertion.nativeArityRight) {
			witnessAliases.push(`type NativeArity${assertion.id} = ${assertion.nativeArityRight};`);
		}
	}
	writeFileSync(probe, [...imports, ...witnessAliases].join('\n'));
	const witnessProgram = createTypeEvidenceProgram([probe, ...entries.values()], parsed.options);
	const witnessChecker = witnessProgram.getTypeChecker();
	const witnessByName = new Map(
		witnessProgram
			.getSourceFile(probe)
			.statements.filter(ts.isTypeAliasDeclaration)
			.map(function (statement) {
				return [statement.name.text, statement];
			}),
	);
	const keySets = new Map();
	const syntheticKeys = new Set([
		'nativeEvent',
		'persist',
		'isDefaultPrevented',
		'isPropagationStopped',
	]);
	for (const assertion of assertions) {
		const witnessNode = witnessByName.get(`Witness${assertion.id}`);
		if (!witnessNode) {
			throw new Error(`Missing public contract witness for ${assertion.name}`);
		}
		const witness = witnessChecker.getTypeFromTypeNode(witnessNode.type);
		const parts = witness.isUnion?.() ? witness.types : [witness];
		const filtered = parts.filter((part) => {
			if (part.value === '$$typeof' || (assertion.context && part.value !== 'Provider'))
				return false;
			return (
				!['BaseUIEvent', 'MaybeBaseUIEvent'].includes(assertion.name) ||
				!syntheticKeys.has(part.value)
			);
		});
		if (
			filtered.some(
				(part) =>
					part.flags & (ts.TypeFlags.Any | ts.TypeFlags.Unknown) ||
					(!part.isLiteral?.() &&
						!(
							part.flags &
							(ts.TypeFlags.Never |
								ts.TypeFlags.String |
								ts.TypeFlags.Number |
								ts.TypeFlags.ESSymbol |
								ts.TypeFlags.UniqueESSymbol)
						)),
			)
		) {
			throw new Error(
				`Public witness did not resolve to concrete keys or arity: ${assertion.name}`,
			);
		}
		let expected =
			filtered
				.map((part) =>
					part.flags & ts.TypeFlags.UniqueESSymbol &&
					part.symbol?.declarations?.some((node) => node.getSourceFile().hasNoDefaultLib)
						? `typeof Symbol.${part.symbol.name}`
						: witnessChecker.typeToString(part, undefined, ts.TypeFormatFlags.NoTruncation),
				)
				.sort()
				.join(' | ') || 'never';
		if (assertion.callable) {
			const nativeArityNode = witnessByName.get(`NativeArity${assertion.id}`);
			if (!nativeArityNode) {
				throw new Error(`Missing native arity witness for ${assertion.name}`);
			}
			const nativeArity = literalUnion(
				witnessChecker.getTypeFromTypeNode(nativeArityNode.type),
				witnessChecker,
			);
			const extensionKey = `${assertion.specifier}#${assertion.name}`;
			const extension = callableArityExtensions[extensionKey];
			if (extension) {
				const documented = extension.length;
				if (nativeArity !== documented) {
					throw new Error(
						`Documented arity ${documented} does not match native ${nativeArity} for ${extensionKey}`,
					);
				}
				for (const value of unionMembers(expected)) {
					if (!unionMembers(documented).has(value)) {
						throw new Error(`Documented arity for ${extensionKey} dropped upstream arity ${value}`);
					}
				}
				expected = documented;
				assertion.extensionReason = extension.reason;
			} else if (nativeArity !== expected) {
				throw new Error(
					`Native arity ${nativeArity} differs from upstream ${expected} for ${extensionKey}; record audit/published-contract-extensions.json`,
				);
			}
		}
		let left;
		if (assertion.callable) left = `Parameters<${assertion.native}>['length']`;
		else if (expected === 'never') left = `keyof ${assertion.native}`;
		else {
			if (!keySets.has(expected)) keySets.set(expected, `PublishedKeys${keySets.size}`);
			left = `keyof Pick<${assertion.native}, ${keySets.get(expected)}>`;
		}
		const contract = assertion.platform
			? `type Contract${assertion.id} = Assert<Equal<${assertion.native}, ${assertion.platform}>>;`
			: `type Contract${assertion.id} = Assert<Equal<${left}, ${keySets.get(expected) ?? expected}>>;`;
		assertion.proof = assertion.extensionReason
			? `// Octane compatibility: ${assertion.extensionReason}\n${contract}`
			: contract;
	}
	// Factor identical membership patterns, so the many component contracts share
	// their literal HTML attribute keys without repeating thousands of lines.
	const memberships = new Map();
	for (const [keys, name] of keySets)
		for (const key of keys.split(' | ')) {
			if (!memberships.has(key)) memberships.set(key, []);
			memberships.get(key).push(name);
		}
	const groups = new Map();
	for (const [key, names] of memberships) {
		const membership = names.join(',');
		if (!groups.has(membership)) groups.set(membership, []);
		groups.get(membership).push(key);
	}
	const pieces = new Map([...keySets.values()].map((name) => [name, []]));
	let groupCount = 0;
	for (const [membership, keys] of groups) {
		const piece = keys.length > 1 ? `SharedKeys${groupCount++}` : keys[0];
		if (keys.length > 1) output.push(`type ${piece} = ${keys.join(' | ')};`);
		for (const name of membership.split(',')) pieces.get(name).push(piece);
	}
	output.push(
		...[...pieces].map(([name, parts]) => `type ${name} = ${parts.join(' | ')};`),
		'',
		...assertions.map(({ proof }) => proof),
		...extraProofs.map(function (extra) {
			if (!extra.length) {
				throw new Error(`Additional export ${extra.name} is missing a documented arity`);
			}
			const contract = `type Contract${extra.id} = Assert<Equal<Parameters<${extra.native}>['length'], ${extra.length}>>;`;
			return extra.reason ? `// Octane compatibility: ${extra.reason}\n${contract}` : contract;
		}),
	);
	const destination = path.join(folder, 'published-contract.ts');
	const { format } = await import('prettier');
	const source = await format(`${output.join('\n')}\n`, {
		parser: 'typescript',
		...(await (await import('prettier')).resolveConfig(destination)),
	});
	if (process.argv.includes('--check')) {
		if (readFileSync(destination, 'utf8') !== source)
			throw new Error('Published consumer assertions have drifted; regenerate them.');
	} else writeFileSync(destination, source);
	console.log(`${manifest.name}: ${specifiers.length} entries, ${count} public export assertions`);
} finally {
	unlinkSync(probe);
}
