// Render the Strong diagnostic catalog into every place that documents it.
//
// packages/octane/src/compiler/strong-diagnostics.js is the single source. This
// script writes generated regions into the website's Strong mode page,
// docs/strong-compiler-checks.md, and llms.txt, and a JSON copy for the MCP
// server, which cannot import the compiler at runtime. The CLI snapshot is
// written by scripts/generate-cli-data.mjs from the same module.
//
// Regenerate with `pnpm strong:diagnostics`; CI runs `pnpm strong:diagnostics:check`.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import {
	STRONG_DIAGNOSTICS,
	STRONG_DIAGNOSTIC_SECTIONS,
	STRONG_RECIPES,
} from '../packages/octane/src/compiler/strong-diagnostics.js';
import { STRONG_DOCS_URL, strongDocsUrl } from '../packages/octane/src/compiler/strong-fixes.js';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'packages/octane/src/compiler/strong-diagnostics.js';
const COMMAND = 'pnpm strong:diagnostics';

export const OUTPUTS = {
	page: 'website/src/content/docs/strong-mode.mdx',
	checks: 'docs/strong-compiler-checks.md',
	llms: 'website/public/llms.txt',
	mcp: 'packages/octane-mcp-server/src/strong-diagnostics.json',
};

function fail(message) {
	throw new Error(`Invalid Strong diagnostic catalog (${SOURCE}): ${message}`);
}

export function validateCatalog() {
	const sections = new Set(STRONG_DIAGNOSTIC_SECTIONS.map((section) => section.id));
	const codes = new Set();
	for (const entry of STRONG_DIAGNOSTICS) {
		if (!/^OCTANE_[A-Z0-9_]+$/.test(entry.code)) fail(`malformed code ${entry.code}.`);
		if (codes.has(entry.code)) fail(`${entry.code} is listed twice.`);
		codes.add(entry.code);
		if (!sections.has(entry.section)) fail(`${entry.code} has unknown section ${entry.section}.`);
		if (entry.severity !== 'error' && entry.severity !== 'hint') {
			fail(`${entry.code} severity must be "error" or "hint".`);
		}
		for (const field of ['detects', 'replacement']) {
			if (typeof entry[field] !== 'string' || entry[field].trim() === '') {
				fail(`${entry.code} needs ${field}.`);
			}
			assertPortableMarkdown(entry[field], `${entry.code}.${field}`);
		}
	}
	const recipes = new Set();
	for (const recipe of STRONG_RECIPES) {
		if (!/^[a-z][a-z-]*$/.test(recipe.id)) fail(`malformed recipe id ${recipe.id}.`);
		if (recipes.has(recipe.id)) fail(`recipe ${recipe.id} is listed twice.`);
		recipes.add(recipe.id);
		if (recipe.codes.length === 0) fail(`recipe ${recipe.id} names no codes.`);
		for (const code of recipe.codes) {
			if (!codes.has(code)) fail(`recipe ${recipe.id} names unknown code ${code}.`);
		}
		for (const field of ['title', 'react', 'strong', 'before', 'after', 'note']) {
			if (typeof recipe[field] !== 'string' || recipe[field].trim() === '') {
				fail(`recipe ${recipe.id} needs ${field}.`);
			}
		}
		assertPortableMarkdown(recipe.note, `recipe ${recipe.id}.note`);
		assertPortableMarkdown(recipe.title, `recipe ${recipe.id}.title`);
	}
}

// The same prose lands in MDX, a Markdown table, and plain text. Outside code
// spans, MDX would read braces and angle brackets as JSX and a table would
// read a pipe as a cell boundary, so the catalog keeps them inside backticks.
function assertPortableMarkdown(text, where) {
	const prose = text.replace(/`[^`]*`/g, '');
	if (/[{}<>|]/.test(prose)) {
		fail(`${where} has {, }, <, >, or | outside a code span.`);
	}
}

const anchor = (code) => code.toLowerCase().replaceAll('_', '-');
const bySection = (id) => STRONG_DIAGNOSTICS.filter((entry) => entry.section === id);
const withDirective = (source) => `"use strong";\n${source}`;

function region(text, start, end, body, file) {
	const from = text.indexOf(start);
	const to = text.indexOf(end);
	if (from === -1 || to === -1 || to < from) {
		throw new Error(`${file} is missing the generated region ${start} … ${end}.`);
	}
	return `${text.slice(0, from + start.length)}\n${body}\n${text.slice(to)}`;
}

function checksTable(section) {
	const rows = bySection(section.id).map(
		(entry) =>
			`| [\`${entry.code}\`](${strongDocsUrl(entry.code)}) | ${entry.detects} | ${entry.replacement} |`,
	);
	return ['| Diagnostic | What it detects | Replacement |', '| --- | --- | --- |', ...rows].join(
		'\n',
	);
}

function renderChecks(text) {
	for (const section of STRONG_DIAGNOSTIC_SECTIONS) {
		text = region(
			text,
			`<!-- strong-diagnostics:${section.id}:start (generated by \`${COMMAND}\` from ${SOURCE}) -->`,
			`<!-- strong-diagnostics:${section.id}:end -->`,
			checksTable(section),
			OUTPUTS.checks,
		);
	}
	return text;
}

function renderRecipesMdx() {
	const parts = [];
	for (const recipe of STRONG_RECIPES) {
		parts.push(
			`<h3 id="recipe-${recipe.id}">${recipe.title}</h3>`,
			'',
			`React: \`${recipe.react}\``,
			'',
			`Strong: \`${recipe.strong}\``,
			'',
			`Reports ${recipe.codes.map((code) => `[\`${code}\`](#${anchor(code)})`).join(' and ')}.`,
			'',
			'```tsx',
			withDirective(recipe.before).trimEnd(),
			'```',
			'',
			'```tsx',
			withDirective(recipe.after).trimEnd(),
			'```',
			'',
			recipe.note,
			'',
		);
	}
	return parts.join('\n');
}

function renderReferenceMdx() {
	const parts = [];
	for (const section of STRONG_DIAGNOSTIC_SECTIONS) {
		parts.push(`<h3 id="diagnostics-${section.id}">${section.title}</h3>`, '');
		for (const entry of bySection(section.id)) {
			parts.push(
				`<h4 id="${anchor(entry.code)}">`,
				`\t<code>${entry.code}</code>`,
				'</h4>',
				'',
				`${entry.severity === 'hint' ? '**Hint.** ' : ''}${entry.detects}`,
				'',
				`**Replacement.** ${entry.replacement}`,
				'',
			);
		}
	}
	return parts.join('\n');
}

function renderPage(text) {
	text = region(
		text,
		`{/* strong-diagnostics:recipes:start (generated by \`${COMMAND}\` from ${SOURCE}) */}`,
		'{/* strong-diagnostics:recipes:end */}',
		`\n${renderRecipesMdx()}`,
		OUTPUTS.page,
	);
	return region(
		text,
		`{/* strong-diagnostics:reference:start (generated by \`${COMMAND}\` from ${SOURCE}) */}`,
		'{/* strong-diagnostics:reference:end */}',
		`\n${renderReferenceMdx()}`,
		OUTPUTS.page,
	);
}

function renderLlms(text) {
	const lines = ['Migration recipes, React idiom → Strong replacement:', ''];
	for (const recipe of STRONG_RECIPES) {
		lines.push(`- ${recipe.title}: \`${recipe.react}\` → \`${recipe.strong}\``);
	}
	lines.push('', 'Every Strong diagnostic and its replacement:', '');
	for (const section of STRONG_DIAGNOSTIC_SECTIONS) {
		lines.push(`${section.title}:`, '');
		for (const entry of bySection(section.id)) {
			lines.push(
				`- \`${entry.code}\`${entry.severity === 'hint' ? ' (hint)' : ''}: ${entry.replacement}`,
			);
		}
		lines.push('');
	}
	lines.push(`Each code is documented at ${STRONG_DOCS_URL}#<code-in-kebab-case>.`);
	return region(
		text,
		`<!-- strong-diagnostics:llms:start (generated by \`${COMMAND}\` from ${SOURCE}) -->`,
		'<!-- strong-diagnostics:llms:end -->',
		`\n${lines.join('\n')}\n`,
		OUTPUTS.llms,
	);
}

function renderMcp() {
	return JSON.stringify({
		$comment: `Generated by \`${COMMAND}\` from ${SOURCE}. Do not edit.`,
		docsUrl: STRONG_DOCS_URL,
		sections: STRONG_DIAGNOSTIC_SECTIONS,
		diagnostics: STRONG_DIAGNOSTICS.map((entry) => ({ ...entry, url: strongDocsUrl(entry.code) })),
		recipes: STRONG_RECIPES.map((recipe) => ({
			...recipe,
			before: withDirective(recipe.before),
			after: withDirective(recipe.after),
		})),
	});
}

const RENDERERS = {
	page: renderPage,
	checks: renderChecks,
	llms: renderLlms,
	mcp: renderMcp,
};

/**
 * Formats like `pnpm format` would, so `format:check` and `--check` agree.
 * Markdown and llms.txt are hand-authored and outside Prettier's reach.
 */
async function formatted(file, text) {
	if (file.endsWith('.md') || file.endsWith('.txt')) return text;
	const absolute = path.join(REPO, file);
	return format(text, { ...(await resolveConfig(absolute)), filepath: absolute });
}

async function main() {
	validateCatalog();
	const check = process.argv.includes('--check');
	const stale = [];
	for (const [key, file] of Object.entries(OUTPUTS)) {
		const absolute = path.join(REPO, file);
		let current = '';
		try {
			current = readFileSync(absolute, 'utf8');
		} catch {
			if (key !== 'mcp') throw new Error(`${file} does not exist.`);
		}
		const next = await formatted(file, RENDERERS[key](current));
		if (next === current) continue;
		if (check) stale.push(file);
		else writeFileSync(absolute, next);
	}
	if (stale.length > 0) {
		console.error(`Out of date: ${stale.join(', ')}. Run \`${COMMAND}\`.`);
		process.exit(1);
	}
	console.log(
		check
			? 'Strong diagnostic documentation is up to date.'
			: `Rendered ${STRONG_DIAGNOSTICS.length} Strong diagnostics and ${STRONG_RECIPES.length} recipes.`,
	);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
